#!/usr/bin/env python3
"""Build the replaceable CGAL solid-repair adapter; no frontend toolchain required."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tarfile
import urllib.request
import gzip

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / 'build/stl-solid-repair'
SOURCES = [
    ('CGAL-6.1.1.tar.xz', 'https://github.com/CGAL/cgal/releases/download/v6.1.1/CGAL-6.1.1.tar.xz', '52506935f70e247ed2777e3c65f20e86f79208c2a2d0e180ae7475daf11c96ef'),
    ('boost_1_83_0.tar.bz2', 'https://archives.boost.io/release/1.83.0/source/boost_1_83_0.tar.bz2', '6478edfe2f3305127cffe8caf73ea0176c53769f4bf1585be237eb30798c3b8e'),
]

def main():
    (CACHE / 'downloads').mkdir(parents=True, exist_ok=True)
    for name, url, digest in SOURCES:
        archive = CACHE / 'downloads' / name
        if not archive.exists():
            urllib.request.urlretrieve(url, archive)
        if hashlib.file_digest(archive.open('rb'), 'sha256').hexdigest() != digest:
            raise ValueError('Source archive checksum mismatch: ' + name)
        # Refresh the exact pinned headers; no locally modified vendor tree.
        with tarfile.open(archive) as source:
            members = source.getmembers()
            if name.startswith('boost'):
                members = [m for m in members if m.name.startswith('boost_1_83_0/boost/') or m.name == 'boost_1_83_0/LICENSE_1_0.txt']
            source.extractall(CACHE, members=members, filter='data')
    sdk = Path(os.environ.get('SPJUTSIM_EMSDK_ROOT', str(ROOT / 'build/emsdk')))
    compiler = os.environ.get('EMXX', str(sdk / 'upstream/emscripten/em++'))
    output = CACHE / 'repair.js'
    # ALWAYS_ROUND_TO_NEAREST makes CGAL interval arithmetic expand with
    # nextafter; WASM cannot change hardware rounding modes. MP_Float keeps
    # exact predicates without GMP/MPFR or a second multiprecision dependency.
    subprocess.run([compiler, str(ROOT / 'native/stl-repair/repair.cpp'),
        '-I' + str(CACHE / 'CGAL-6.1.1/include'), '-I' + str(CACHE / 'boost_1_83_0'),
        '-std=c++17', '-Os', '-flto', '-DNDEBUG', '-ffile-prefix-map='+str(ROOT)+'=/SpjutSim-FEA', '-DCGAL_DISABLE_GMP=1',
        '-DCGAL_DISABLE_MPFR=1', '-DCGAL_DO_NOT_USE_BOOST_MP=1',
        '-DCGAL_ALWAYS_ROUND_TO_NEAREST=1', '-fexceptions', '-sDISABLE_EXCEPTION_CATCHING=0',
        '-sSINGLE_FILE=1', '-sMODULARIZE=1', '-sEXPORT_NAME=createStlSolidRepair',
        '-sENVIRONMENT=worker', '-sFILESYSTEM=0', '-sALLOW_MEMORY_GROWTH=1',
        '-sINITIAL_MEMORY=16777216', '-sMAXIMUM_MEMORY=536870912', '-sASSERTIONS=0', '-sMALLOC=emmalloc',
        '-sEXPORTED_FUNCTIONS=["_malloc","_free","_repair_api_version","_repair_solid","_repair_vertex_count","_repair_facet_count","_repair_positions","_repair_triangles","_repair_vertex_sources","_repair_face_sources","_repair_face_changed","_repair_filled_voids"]',
        '-o', str(output)], check=True, cwd=ROOT)
    source = output.read_text()
    wrapped = '/* Generated by tools/build-stl-repair.py. CGAL 6.1.1 adapter; GPL-3.0-or-later.\n * Native source: native/stl-repair/repair.cpp\n * Runtime SHA-256: ' + hashlib.sha256(source.encode()).hexdigest() + ' */\n(function(root){\n  var runtime=root.SpjutsimLocalRuntimeWorkers=root.SpjutsimLocalRuntimeWorkers||{};\n  runtime.solidRepair=' + json.dumps(source) + ';\n}(globalThis));\n'
    compressed = len(gzip.compress(wrapped.encode(), mtime=0))
    if len(wrapped.encode()) > 2*1024*1024 or compressed > 768*1024:
        raise ValueError('Solid-repair runtime exceeds its reviewed packaging budget')
    (ROOT / 'web/generated/local-runtime/solid-repair-runtime-source.js').write_text(wrapped)
    print(f'Solid repair: {len(wrapped.encode())} bytes, {compressed} gzip bytes')

if __name__ == '__main__':
    main()
